console.log("\n[与 ICU 中文历法逐日交叉对照（已知分歧除外）]");
t("1900–2100 每天与 ICU 一致（除已知分歧）", () => {
  const ICU = new Intl.DateTimeFormat("zh-CN-u-ca-chinese", {
    year: "numeric", month: "long", day: "numeric",
  });
  const MONTH_MAP = {
    正月: 1, 二月: 2, 三月: 3, 四月: 4, 五月: 5, 六月: 6, 七月: 7, 八月: 8,
    九月: 9, 十月: 10, 十一月: 11, 十二月: 12, 冬月: 11, 腊月: 12,
  };

  const startUTC = Date.UTC(1900, 0, 31);
  const endUTC = Date.UTC(2100, 11, 31);
  let mismatches = [];
  let checked = 0;
  let skipped = 0;

  for (let ts = startUTC; ts <= endUTC; ts += 86400000) {
    const dt = new Date(ts);
    const y = dt.getUTCFullYear();
    const m = dt.getUTCMonth() + 1;
    const d = dt.getUTCDate();

    if (inDivergence(y, m, d)) { skipped++; continue; }

    const parts = ICU.formatToParts(dt);
    const get = (ty) => (parts.find((p) => p.type === ty) || {}).value;
    const rawMonth = String(get("month") || "");
    const ref = {
      year: Number(get("relatedYear")),
      month: MONTH_MAP[rawMonth.replace("闰", "")],
      day: Number(get("day")),
      isLeap: rawMonth.startsWith("闰"),
    };
    const mine = solar2lunar(y, m, d);
    if (!mine || !ref.month) {
      mismatches.push(`${y}-${m}-${d} 解析失败`);
      continue;
    }
    checked++;
    if (mine.year !== ref.year || mine.month !== ref.month || mine.day !== ref.day || mine.isLeap !== ref.isLeap) {
      mismatches.push(
        `${y}-${m}-${d} 我方 ${mine.year}/${mine.isLeap ? "闰" : ""}${mine.month}/${mine.day}` +
          ` ICU ${ref.year}/${ref.isLeap ? "闰" : ""}${ref.month}/${ref.day}`
      );
      if (mismatches.length > 8) break;
    }
  }

  if (mismatches.length) {
    assert.fail(`比对 ${checked} 天，${mismatches.length} 处不一致：\n      ` + mismatches.join("\n      "));
  }
  console.log(`      （比对 ${checked} 天，跳过已知分歧 ${skipped} 天，全部一致）`);
});

