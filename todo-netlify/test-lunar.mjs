t("每个农历月首的日期与官方一致（2474 个）", () => {
  const bad = [];
  let checked = 0;

  for (const line of HKO) {
    const [yearStr, cny, leapStr, lensStr] = line.split("|");
    const year = Number(yearStr);
    const leap = Number(leapStr);
    const lens = lensStr.split(",").map(Number);

    // 期望的月份顺序：正月、二月……遇到闰月时在同名月之后插一个闰月
    const seq = [];
    for (let m = 1; m <= 12; m++) {
      seq.push({ month: m, isLeap: false });
      if (leap === m) seq.push({ month: m, isLeap: true });
    }
    if (seq.length !== lens.length) {
      bad.push(`${year} 年官方数据月数不符（${lens.length} vs ${seq.length}）`);
      continue;
    }

    let ts = Date.UTC(year, Number(cny.slice(0, 2)) - 1, Number(cny.slice(2, 4)));
    for (let i = 0; i < lens.length; i++) {
      const dt = new Date(ts);
      const y = dt.getUTCFullYear();
      const mo = dt.getUTCMonth() + 1;
      const d = dt.getUTCDate();
      checked++;

      const got = solar2lunar(y, mo, d);
      const exp = seq[i];
      if (!got) {
        bad.push(`${year} 月首 ${dt.toISOString().slice(0, 10)} 返回 null`);
      } else if (
        got.year !== year ||
        got.day !== 1 ||
        got.month !== exp.month ||
        got.isLeap !== exp.isLeap
      ) {
        bad.push(
          `${y}-${String(mo).padStart(2, "0")}-${String(d).padStart(2, "0")} 应为 ${year} 年 ` +
            `${exp.isLeap ? "闰" : ""}${exp.month}月初一，得到 ${got.year} 年 ` +
            `${got.isLeap ? "闰" : ""}${got.month}月${got.day}日`
        );
      }
      ts += lens[i] * 86400000;
    }
  }

  assert.equal(bad.length, 0, `共核对 ${checked} 个月首，` + bad.slice(0, 5).join("；"));
  console.log("      （核对 " + checked + " 个农历月首，全部与 HKO 官方数据一致）");
  assert.ok(checked >= 2400, "核对数量偏少：" + checked);
});

